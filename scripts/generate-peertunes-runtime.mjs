import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

// Turns the vendored PeerTunes app under assets/peertunes into one module the
// Bare bundle can carry, since bare-pack only packs JavaScript. Output is
// sorted so regenerating from the same files never changes the committed file.

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)))
const sourceDir = join(root, 'assets', 'peertunes')
const output = join(root, 'backend', 'peertunes', 'peertunes-runtime.mjs')

const SKIPPED_FILES = new Set(['LICENSE', 'manifest.json'])
const TEXT_EXTENSIONS = new Set(['.css', '.html', '.js', '.json', '.mjs', '.svg', '.txt', '.webmanifest'])

async function collectFiles (dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue
    const entryPath = join(dir, entry.name)

    if (entry.isDirectory()) {
      files.push(...await collectFiles(entryPath))
    } else if (entry.isFile() && !SKIPPED_FILES.has(entry.name)) {
      files.push(entryPath)
    }
  }

  return files
}

const files = (await collectFiles(sourceDir)).sort()
const assets = {}

for (const filePath of files) {
  const key = relative(sourceDir, filePath).split(sep).join('/')
  const extension = key.slice(key.lastIndexOf('.')).toLowerCase()
  const bytes = await readFile(filePath)

  assets[key] = TEXT_EXTENSIONS.has(extension)
    ? { encoding: 'utf8', content: bytes.toString('utf8') }
    : { encoding: 'base64', content: bytes.toString('base64') }
}

await mkdir(dirname(output), { recursive: true })
await writeFile(output, [
  '/* eslint-disable */',
  '// Generated by scripts/generate-peertunes-runtime.mjs from assets/peertunes.',
  `const peertunesAssets = ${JSON.stringify(assets)}`,
  '',
  'export default peertunesAssets',
  ''
].join('\n'))
